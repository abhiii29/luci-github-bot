import { describe, it, expect, vi } from "vitest";
import type { SplitGitHub } from "../src/split.js";
import { handleMergedPr } from "../src/merge-handler.js";
import * as split from "../src/split.js";

vi.mock("../src/split.js", async (importOriginal) => {
  const actual = await importOriginal<typeof split>();
  return { ...actual, nextPartAfterMerge: vi.fn() };
});

const gh = {
  addAssignees: vi.fn(),
  createComment: vi.fn(),
} as unknown as SplitGitHub;

describe("handleMergedPr", () => {
  it("ignores if not merged", async () => {
    expect(await handleMergedPr(gh, "r", { merged: false, body: null, user: { login: "bot" } }, "bot")).toEqual({ kind: "ignored", reason: "not merged" });
  });

  it("ignores non-bot body", async () => {
    expect(await handleMergedPr(gh, "r", { merged: true, body: "hello", user: { login: "bot" } }, "bot")).toEqual({ kind: "ignored", reason: "not a bot PR" });
  });

  it("ignores wrong author", async () => {
    expect(await handleMergedPr(gh, "r", { merged: true, body: "generated by luci-github-bot", user: { login: "alice" } }, "bot")).toEqual({ kind: "ignored", reason: "not authored by bot" });
  });

  it("ignores no Closes link", async () => {
    expect(await handleMergedPr(gh, "r", { merged: true, body: "generated by luci-github-bot", user: { login: "bot" } }, "bot")).toEqual({ kind: "ignored", reason: "no linked issue" });
  });

  it("ignores null from nextPartAfterMerge", async () => {
    (split.nextPartAfterMerge as ReturnType<typeof vi.fn>).mockResolvedValue(null);
    expect(await handleMergedPr(gh, "r", { merged: true, body: "generated by luci-github-bot\nCloses #123", user: { login: "bot" } }, "bot")).toEqual({ kind: "ignored", reason: "not a split part" });
  });

  it("handles next", async () => {
    (split.nextPartAfterMerge as ReturnType<typeof vi.fn>).mockResolvedValue({ kind: "next" as const, issue: 456, parent: 123 });
    const res = await handleMergedPr(gh, "r", { merged: true, body: "generated by luci-github-bot\nCloses #123", user: { login: "bot" } }, "bot");
    expect(res).toEqual({ kind: "next", issue: 456, parent: 123 });
    expect(gh.addAssignees).toHaveBeenCalledWith("r", 456, ["bot"]);
    expect(gh.createComment).toHaveBeenCalledWith("r", 123, "➡️ Part merged; starting next part #456.");
  });

  it("handles done", async () => {
    (split.nextPartAfterMerge as ReturnType<typeof vi.fn>).mockResolvedValue({ kind: "done" as const, parent: 123 });
    const res = await handleMergedPr(gh, "r", { merged: true, body: "generated by luci-github-bot\nCloses #123", user: { login: "bot" } }, "bot");
    expect(res).toEqual({ kind: "done", parent: 123 });
    expect(gh.createComment).toHaveBeenCalledWith("r", 123, "✅ All parts merged.");
  });
});