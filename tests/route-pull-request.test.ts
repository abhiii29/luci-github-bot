import { describe, it, expect, vi, beforeEach } from "vitest";

const handleMergedPr = vi.fn();
vi.mock("../src/merge-handler.js", () => ({ handleMergedPr }));

const { routeEvent } = await import("../src/webhook.js");

const config = { monitoredRepos: ["o/r"], githubToken: "t", botUsername: "bot" } as never;
const pr = { merged: true, body: "generated by luci-github-bot\nCloses #8", user: { login: "bot" } };

describe("routeEvent pull_request", () => {
  beforeEach(() => handleMergedPr.mockReset());

  it("passes a closed PR in a monitored repo to the merge handler", async () => {
    handleMergedPr.mockResolvedValue({ kind: "next", issue: 9, parent: 7 });
    const r = await routeEvent("pull_request", { action: "closed", pull_request: pr, repository: { full_name: "o/r" } }, undefined, config);
    expect(handleMergedPr).toHaveBeenCalledWith(expect.anything(), "o/r", pr, "bot");
    expect(r.body).toEqual({ status: "pull_request", kind: "next", issue: 9, parent: 7 });
  });

  it("ignores other PR actions and unmonitored repos", async () => {
    await routeEvent("pull_request", { action: "opened", pull_request: pr, repository: { full_name: "o/r" } }, undefined, config);
    await routeEvent("pull_request", { action: "closed", pull_request: pr, repository: { full_name: "x/y" } }, undefined, config);
    expect(handleMergedPr).not.toHaveBeenCalled();
  });
});
