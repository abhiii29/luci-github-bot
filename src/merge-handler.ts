import type { SplitGitHub } from "./split.js";
import { nextPartAfterMerge } from "./split.js";

export interface MergedPr {
  merged: boolean;
  body: string | null;
  user: { login: string };
}

export type MergeOutcome =
  | { kind: "ignored"; reason: string }
  | { kind: "next"; issue: number; parent: number }
  | { kind: "done"; parent: number };

export async function handleMergedPr(
  gh: SplitGitHub,
  repo: string,
  pr: MergedPr,
  botUsername: string
): Promise<MergeOutcome> {
  if (!pr.merged) {
    return { kind: "ignored", reason: "not merged" };
  }
  if (!pr.body?.includes("generated by luci-github-bot")) {
    return { kind: "ignored", reason: "not a bot PR" };
  }
  if (pr.user.login.toLowerCase() !== botUsername.toLowerCase()) {
    return { kind: "ignored", reason: "not authored by bot" };
  }
  const match = pr.body?.match(/\bCloses #(\d+)\b/);
  if (!match) {
    return { kind: "ignored", reason: "no linked issue" };
  }
  const issueNumber = parseInt(match[1], 10);
  const result = await nextPartAfterMerge(gh, repo, issueNumber, botUsername);
  if (!result) {
    return { kind: "ignored", reason: "not a split part" };
  }
  if (result.kind === "next") {
    await gh.addAssignees(repo, result.issue, [botUsername]);
    await gh.createComment(repo, result.parent, "➡️ Part merged; starting next part #" + result.issue + ".");
    return result;
  }
  await gh.createComment(repo, result.parent, "✅ All parts merged.");
  return result;
}